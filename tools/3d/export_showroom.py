# ----------------------------------------------------------------------------- helpers
def rel(p):
    return os.path.relpath(p, SITE).replace("\\", "/")


def tris(objs):
    return sum(sum(len(p.vertices) - 2 for p in o.data.polygons) for o in objs if o.type == "MESH")


def open_blend(path):
    bpy.ops.wm.open_mainfile(filepath=path, load_ui=False)   # read-only use; never saved


def keep_only(objs):
    """Drop everything else from the in-memory file; bake transforms; link to the active scene."""
    keep = set(objs)
    for o in list(bpy.data.objects):
        if o not in keep:
            bpy.data.objects.remove(o, do_unlink=True)
    scene = bpy.context.scene
    for o in objs:
        for c in list(o.users_collection):
            c.objects.unlink(o)
        scene.collection.objects.link(o)
        o.hide_viewport = o.hide_render = False
        o.hide_set(False)
    return objs


def bake(objs, extra=Matrix()):
    bpy.context.view_layer.update()     # matrix_world of freshly placed objects is stale until this
    for o in objs:
        o.data = o.data.copy()
        mw = extra @ o.matrix_world
        o.parent = None
        o.data.transform(mw)
        o.matrix_world = Matrix()


def drop_outliers(objs):
    """Delete stray vertices far outside the model (source defect: zombieBruteOutfit legs have verts at y=-180).
    Box = 10..90 percentile of all vertices, padded by 100% of its size on every side."""
    import bmesh
    sorted_axes = [sorted(v.co[i] for o in objs for v in o.data.vertices) for i in range(3)]
    n = len(sorted_axes[0])
    lo = [a[int(n * 0.1)] for a in sorted_axes]
    hi = [a[int(n * 0.9)] for a in sorted_axes]
    pad = [(h - l) * 1.0 + 0.05 for l, h in zip(lo, hi)]
    removed = 0
    for o in objs:
        bm = bmesh.new()
        bm.from_mesh(o.data)
        bad = [v for v in bm.verts if any(not (lo[i] - pad[i] <= v.co[i] <= hi[i] + pad[i]) for i in range(3))]
        if bad:
            removed += len(bad)
            bmesh.ops.delete(bm, geom=bad, context="VERTS")
            bm.to_mesh(o.data)
        bm.free()
    return removed


def decimate(objs, target):
    total = tris(objs)
    big = [o for o in objs if tris([o]) >= SMALL_PIECE]
    small = total - tris(big)
    if not target or total <= max(target, DECIMATE_ABOVE) or not big:
        return False
    ratio = max(0.08, min(1.0, (target - small) / max(1, tris(big))))
    dg = bpy.context.evaluated_depsgraph_get()
    for o in big:
        m = o.modifiers.new("dec", "DECIMATE")
        m.ratio = ratio
        m.use_collapse_triangulate = True
        dg.update()
        me = bpy.data.meshes.new_from_object(o.evaluated_get(dg))
        o.modifiers.remove(m)
        o.data = me
    return True


def join(objs):
    objs = [o for o in objs if o.type == "MESH"]
    with bpy.context.temp_override(active_object=objs[0], object=objs[0], selected_objects=objs,
                                   selected_editable_objects=objs):
        bpy.ops.object.join()
    return objs[0]


def normalize(o, height=1.0, max_side=2.0):
    """Scale to `height` metres (Blender Z), but never wider than `max_side` (flat models such as a dragon
    with spread wings), and move the base centre to the origin."""
    vs = [v.co for v in o.data.vertices]
    lo = Vector((min(v.x for v in vs), min(v.y for v in vs), min(v.z for v in vs)))
    hi = Vector((max(v.x for v in vs), max(v.y for v in vs), max(v.z for v in vs)))
    s = min(height / (hi.z - lo.z), max_side / max(hi.x - lo.x, hi.y - lo.y))
    c = Vector(((lo.x + hi.x) / 2, (lo.y + hi.y) / 2, lo.z))
    o.data.transform(Matrix.Scale(s, 4) @ Matrix.Translation(-c))
    o.data.update()
    return s


def export_glb(objs, path):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    for o in bpy.context.scene.objects:
        o.select_set(o in objs)
    bpy.ops.export_scene.gltf(filepath=path, export_format="GLB", use_selection=True, export_apply=True,
                              export_yup=True, export_cameras=False, export_lights=False, export_animations=False,
                              export_vertex_color="ACTIVE", export_extras=False)
    return round(os.path.getsize(path) / 1024, 1)


# ----------------------------------------------------------------------------- poster
def poster(objs, out_webp, view=(0.55, -1.0, 0.38)):
    scene = bpy.context.scene
    try:
        scene.render.engine = "BLENDER_EEVEE"
    except TypeError:
        pass
    scene.render.resolution_x = scene.render.resolution_y = 1024
    scene.render.resolution_percentage = 100
    scene.render.film_transparent = True
    scene.render.image_settings.file_format = "PNG"
    scene.render.image_settings.color_mode = "RGBA"
    try:
        scene.view_settings.view_transform = "Standard"
    except TypeError:
        pass
    world = bpy.data.worlds.new("SR_World")
    world.use_nodes = True
    bg = next(n for n in world.node_tree.nodes if n.type == "BACKGROUND")
    bg.inputs["Color"].default_value = (0.78, 0.8, 0.86, 1)
    bg.inputs["Strength"].default_value = 0.55
    scene.world = world
    made = []
    for name, kind, energy, loc in (("SR_Key", "AREA", 110.0, (-2.2, -3.0, 3.2)), ("SR_Fill", "AREA", 45.0, (3.0, -2.0, 1.6)),
                                    ("SR_Rim", "AREA", 90.0, (0.8, 3.2, 2.6))):
        li = bpy.data.lights.new(name, kind)
        li.energy, li.size = energy, 3.0
        lo = bpy.data.objects.new(name, li)
        lo.location = loc
        lo.rotation_euler = (Vector((0, 0, 0.5)) - Vector(loc)).to_track_quat("-Z", "Y").to_euler()
        scene.collection.objects.link(lo)
        made.append(lo)
    cam = bpy.data.objects.new("SR_Cam", bpy.data.cameras.new("SR_Cam"))
    scene.collection.objects.link(cam)
    made.append(cam)
    pts = [o.matrix_world @ v.co for o in objs for v in o.data.vertices]
    lo = Vector((min(p.x for p in pts), min(p.y for p in pts), min(p.z for p in pts)))
    hi = Vector((max(p.x for p in pts), max(p.y for p in pts), max(p.z for p in pts)))
    centre = (lo + hi) / 2
    radius = (hi - lo).length / 2
    cam.data.lens = 50
    fov = 2 * math.atan(18 / 50)
    d = Vector(view).normalized()     # default: front (-Y in Blender = +Z glTF), 3/4 from the right, slightly above
    cam.location = centre + d * (radius / math.sin(fov / 2) * 0.9)
    cam.rotation_euler = (-d).to_track_quat("-Z", "Y").to_euler()
    scene.camera = cam
    os.makedirs(TMP, exist_ok=True)
    png = os.path.join(TMP, os.path.basename(out_webp)[:-5] + ".png")
    scene.render.filepath = png
    bpy.ops.render.render(write_still=True)
    for o in made:
        bpy.data.objects.remove(o, do_unlink=True)
    return to_webp(png, out_webp, POSTER_KB)


def to_webp(png, out, max_kb, scale=None):
    os.makedirs(os.path.dirname(out), exist_ok=True)
    for q in (88, 80, 72, 64, 56, 48, 40):
        cmd = ["ffmpeg", "-y", "-loglevel", "error", "-i", png]
        if scale:
            cmd += ["-vf", "scale=%d:-2" % scale]
        cmd += ["-c:v", "libwebp", "-quality", str(q), "-pix_fmt", "yuva420p", out]
        subprocess.run(cmd, check=True)
        if os.path.getsize(out) <= max_kb * 1024:
            break
    return round(os.path.getsize(out) / 1024, 1)


# ----------------------------------------------------------------------------- pets
def manifest():
    with open(os.path.join(PETS, "manifest.json"), encoding="utf-8") as fh:
        return json.load(fh)


def rbx_to_bl(v):
    return Vector((v[0], -v[2], v[1]))        # pf_lib.TO_BLENDER


def bl_to_gltf(v):
    return [round(v[0], 4) + 0.0, round(v[2], 4) + 0.0, round(-v[1], 4) + 0.0]


def socket_bl(m, key):
    """Where the part pivot sits in pet space (Blender coords, studs), exactly as build_all.assemble()."""
    s = m["assets"][key]["socket"]
    return rbx_to_bl((s[0], s[1] + m["bodyHeight"], s[2]))


def assemble_pet(combo):
    m = manifest()
    objs = []
    for slot, el in combo.items():
        key = "%s_%s" % (el, slot)
        src = bpy.data.objects[key]
        o = bpy.data.objects.new("pet__" + slot, src.data)
        o.location = socket_bl(m, key)
        bpy.context.scene.collection.objects.link(o)
        objs.append(o)
    return objs


# ----------------------------------------------------------------------------- models
def build(spec):
    if spec["kind"] == "fbx":
        bpy.ops.wm.read_factory_settings(use_empty=True)
        bpy.ops.import_scene.fbx(filepath=spec["src"])
        # Roblox attachment helpers (Fwd/Grip/Up/Ref* boxes) carry the magenta "Marker" material: not geometry
        objs = [o for o in bpy.data.objects if o.type == "MESH"
                and not any(m and m.name.startswith("Marker") for m in o.data.materials)]
    else:
        open_blend(spec["src"])
        if spec["kind"] == "pet":
            objs = assemble_pet(spec["combo"])
        elif spec["kind"] == "prefix":
            objs = [o for o in bpy.data.objects if o.type == "MESH" and o.name.startswith(spec["prefix"])]
        else:
            objs = [o for o in bpy.data.collections[spec["collection"]].all_objects if o.type == "MESH"]
    bake(objs, ROT_180 if spec.get("rot") else Matrix())   # before keep_only: parents must still exist
    keep_only(objs)
    stray = drop_outliers(objs) if spec.get("outliers") else 0   # opt-in: it would clip real wing tips elsewhere
    before = tris(objs)
    dec = decimate(objs, spec.get("target"))
    obj = join(objs)
    obj.name = spec["id"]
    normalize(obj)
    spec["stray"] = stray
    return obj, before, dec


def export_model(spec):
    obj, before, dec = build(spec)
    glb = os.path.join(OUT_MODELS, spec["id"] + ".glb")
    kb = export_glb([obj], glb)
    pkb = poster([obj], os.path.join(OUT_POSTERS, spec["id"] + ".webp"), spec.get("view", (0.55, -1.0, 0.38)))
    after = tris([obj])
    notes = "Source tris %d" % before + ("; decimated (Collapse) to %d" % after if dec else "")
    notes += "; colours: %s" % ("vertex colours (COLOR_0)" if obj.data.color_attributes else "PBR material factors, no textures")
    if spec.get("stray"):
        notes += "; removed %d stray source vertices far outside the model" % spec["stray"]
    notes += "; poster %.1f KB" % pkb
    print("@@ MODEL", spec["id"], before, "->", after, "tris", kb, "KB, poster", pkb, "KB")
    return {"id": spec["id"], "projectSlug": spec["project"], "file": "/models/%s.glb" % spec["id"],
            "poster": "/posters/%s.webp" % spec["id"], "title": spec["title"], "description": spec["desc"],
            "source": rel(spec["src"]), "triangles": after, "sizeKB": kb, "decimated": dec, "animations": [],
            "notes": notes}


def export_parts():
    src = os.path.join(PETS, "assets", "petforge_parts_v2.blend")
    open_blend(src)
    m = manifest()
    # one scale for every part: the all-AIR pet becomes 1 m tall
    probe = assemble_pet({s: "AIR" for s in PART_SLOTS})
    bake(probe, ROT_180)
    zs = [v.co.z for o in probe for v in o.data.vertices]
    scale = 1.0 / (max(zs) - min(zs))
    ground = min(zs)
    for o in probe:
        bpy.data.objects.remove(o, do_unlink=True)
    xf = Matrix.Scale(scale, 4) @ ROT_180

    def place(v_bl):
        return bl_to_gltf(xf @ (v_bl - Vector((0, 0, ground))))   # ground of the AIR pet at y = 0

    def emit(key, out_name):
        o = bpy.data.objects.new(out_name, bpy.data.objects[key].data.copy())
        bpy.context.scene.collection.objects.link(o)
        o.data.transform(xf)            # pivot stays at the origin
        o.data.update()
        kb = export_glb([o], os.path.join(OUT_PARTS, out_name + ".glb"))
        t = tris([o])
        bpy.data.objects.remove(o, do_unlink=True)
        return kb, t

    parts, accessories = [], []
    for el, el_title in PART_ELEMENTS.items():
        for slot, slot_title in PART_SLOTS.items():
            key = "%s_%s" % (el, slot)
            a = m["assets"][key]
            pid = key.lower().replace("_", "-")
            kb, t = emit(key, pid)
            sock = socket_bl(m, key)
            anchors = [bl_to_gltf(xf @ rbx_to_bl(v)) for v in a["ornaments"]]
            parts.append({"id": pid, "element": el, "slot": slot, "file": "/models/pet-parts/%s.glb" % pid,
                          "title": {k: "%s: %s" % (el_title[k], slot_title[k]) for k in ("en", "ru")},
                          "socket": place(sock), "accessoryAnchors": anchors, "idleAnim": a.get("anim"),
                          "triangles": t, "sizeKB": kb, "source": rel(src) + "#" + key})
            print("@@ PART", pid, t, kb)
    for rar, rt in ACCESSORIES.items():
        key = "ORN_%s_%s" % (ACC_SLOT, rar)
        aid = "acc-%s-%s" % (ACC_SLOT.lower(), rar.lower().replace("_", "-"))
        kb, t = emit(key, aid)
        accessories.append({"id": aid, "slot": ACC_SLOT, "rarity": rar, "file": "/models/pet-parts/%s.glb" % aid,
                            "title": L("%s head charm" % rt["en"], "%s аксессуар головы" % rt["ru"]),
                            "triangles": t, "sizeKB": kb, "source": rel(src) + "#" + key})
    data = {
        "units": "m", "up": "+Y", "forward": "+Z",
        "scale": round(scale, 6), "scaleNote": "1 Roblox stud = scale metres; the all-AIR pet is 1 m tall",
        "assembly": "Put each part GLB (origin = its pivot) at its 'socket' (pet space, ground at y=0). "
                    "Put an accessory at part.socket + part.accessoryAnchors[0] of the part in its 'slot'.",
        "slots": [{"id": s, "title": t} for s, t in PART_SLOTS.items()],
        "elements": [{"id": e, "title": t} for e, t in PART_ELEMENTS.items()],
        "parts": parts, "accessories": accessories,
        "source": rel(os.path.join(PETS, "manifest.json")),
    }
    with open(os.path.join(CONTENT, "pet-parts.json"), "w", encoding="utf-8", newline="\n") as fh:
        json.dump(data, fh, ensure_ascii=False, indent=2)
        fh.write("\n")


def write_models(entries):
    path = os.path.join(CONTENT, "models.json")
    old = []
    if os.path.exists(path):
        with open(path, encoding="utf-8") as fh:
            old = json.load(fh)
    by_id = {e["id"]: e for e in old}
    by_id.update({e["id"]: e for e in entries})
    order = [s["id"] for s in MODELS]
    out = sorted(by_id.values(), key=lambda e: order.index(e["id"]) if e["id"] in order else 99)
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        json.dump(out, fh, ensure_ascii=False, indent=2)
        fh.write("\n")


